/**
 * `tossana-agents run --task <id> --resume [--runner <tool>]`: continue a task with another tool, e.g. when one
 * tool hits its usage limit. Keeps the task branch and the round; the orchestrator continues, never restarts.
 *
 * - Only agent statuses (todo, coding, review, testing). A task waiting for a human or closed is never touched.
 * - Uncommitted changes on the task branch are committed as "WIP: handoff from <previous tool>" after a yes
 *   (or --yes in a non-interactive run); otherwise the run stops.
 * - Posts "[AGENT: orchestrator] [RESULT: STARTED]  Resumed with <tool> after <previous tool>" so the dashboard
 *   shows the switch, and records the run in the handoff file (that is how the next resume knows the tool).
 */
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import {
  KitError,
  ROLES,
  appendHandoff,
  formatAgentComment,
  isClosedType,
  isValidTaskId,
  readHandoff,
  statusForRole,
  type AgentComment,
  type AgentConfig,
  type ClickUpClient,
  type Role,
} from '@tossana/agents-core';
import type { CliContext, Project } from '../context.js';
import { clackPrompts } from '../prompts.js';
import { ORCHESTRATOR, adapterFor, formatCommand, resumePrompt } from '../runners.js';

/** The file each runner needs (generated by init/update for that tool). */
export const RUNNER_FILES: Record<string, { tool: string; file: string } | undefined> = {
  opencode: { tool: 'opencode', file: '.opencode/agents/orchestrator.md' },
  'claude-code': { tool: 'claude-code', file: '.claude/agents/orchestrator.md' },
  codex: { tool: 'codex', file: '.codex/orchestrator.md' },
  antigravity: { tool: 'antigravity', file: '.agents/skills/start-task/SKILL.md' },
};

/** Statuses a resume may pick up: everything the agents own. "human" and closed statuses are never touched. */
const RESUMABLE: Role[] = ['todo', 'coding', 'review', 'testing'];

const RUN_HEADING = /— (?:Run started|Resumed) with ([a-z-]+)/g;

/** The tool of the last run recorded in the handoff file, or null. */
export function previousTool(handoff: string | null): string | null {
  const all = [...(handoff ?? '').matchAll(RUN_HEADING)];
  return all.at(-1)?.[1] ?? null;
}

export function recordRunStart(ctx: CliContext, taskId: string, runner: string, resumedAfter?: string): void {
  const heading = resumedAfter ? `Resumed with ${runner} after ${resumedAfter}` : `Run started with ${runner}`;
  appendHandoff(ctx.cwd, taskId, heading, `Tool: ${runner}. Started by tossana-agents run.`, ctx.now());
}

/** Fails with the fix when the chosen tool's files were never generated for this project. */
export function assertToolFiles(cwd: string, config: AgentConfig, runner: string): void {
  const need = RUNNER_FILES[runner];
  if (!need) return; // custom runner: nothing the kit generates
  if (config.tools.includes(need.tool as never) && existsSync(join(cwd, need.file))) return;
  const tools = [...new Set([...config.tools, need.tool])].join(',');
  throw new KitError(
    `${runner} is not set up in this project (${need.file} is missing). Add it first:\n` +
      `  tossana-agents init --yes --tools ${tools}\n  (or add "${need.tool}" to "tools" in agent.config.json and run: tossana-agents update)`,
  );
}

export interface ResumeDeps {
  git: (args: string[]) => { ok: boolean; out: string; err: string };
  runAgent: (command: { cmd: string; args: string[] }) => Promise<number | null>;
  lastResult: (client: ClickUpClient, taskId: string) => Promise<(AgentComment & { rounds: number }) | null>;
}

export async function resumeTask(
  ctx: CliContext,
  project: Project,
  config: AgentConfig,
  client: ClickUpClient | null,
  opts: { task: string; dryRun?: boolean; yes?: boolean; agent?: boolean },
  deps: ResumeDeps,
): Promise<void> {
  const log = (s: string) => ctx.logger.info(s);
  const id = opts.task;
  if (!isValidTaskId(id)) throw new KitError(`invalid task id "${id}"`);
  const runner = config.pipeline.runner;
  assertToolFiles(ctx.cwd, config, runner);

  const branch = `${config.pipeline.branchPrefix}${id}`;
  if (!deps.git(['rev-parse', '--verify', '--quiet', `refs/heads/${branch}`]).ok) {
    throw new KitError(
      `nothing to resume: there is no branch ${branch}. Start the task with: tossana-agents run --task ${id}`,
    );
  }
  const previous = previousTool(readHandoff(ctx.cwd, id)) ?? 'an earlier run';
  const adapter = adapterFor(config, project.env, ctx.exec, ctx.cwd, id);
  const prompt = resumePrompt(id, previous, config.pipeline.baseBranch);
  const command =
    adapter.headless && opts.agent !== false
      ? adapter.buildCommand({ agent: ORCHESTRATOR, prompt, cwd: ctx.cwd })
      : null;

  log(`\n[run] ===== resume ${id} with ${runner} (previous: ${previous}) =====`);
  if (opts.dryRun) {
    log('[run] dry run: nothing is changed');
    log(
      `  git: switch to ${branch} (kept as it is; uncommitted changes would be committed as "WIP: handoff from ${previous}")`,
    );
    log(`  ClickUp: comment "[AGENT: orchestrator] [RESULT: STARTED] … Resumed with ${runner} after ${previous}"`);
    if (command) log(`  $ ${formatCommand(command)}`);
    return;
  }

  // ---------- ClickUp status: only agent statuses ----------
  const task = await client!.getTask(id, { subtasks: false });
  const status = task.status?.status ?? '';
  if (isClosedType(task.status?.type)) throw new KitError(`${id} is closed ("${status}"); it is never resumed.`);
  const role = ROLES.find((r) => statusForRole(config, r).toLowerCase() === status.toLowerCase());
  if (role === 'human') {
    throw new KitError(
      `${id} is waiting for a human ("${status}"); the agents do not touch it. Move it back yourself if more work is needed.`,
    );
  }
  if (!role || !RESUMABLE.includes(role)) {
    throw new KitError(`${id} has status "${status}", which is not an agent status; it is not resumed.`);
  }

  // ---------- git: the existing task branch, never reset ----------
  const current = deps.git(['branch', '--show-current']).out;
  if (current !== branch) {
    const dirtyHere = deps.git(['status', '--porcelain', '--untracked-files=no']).out;
    if (dirtyHere)
      throw new KitError(`you have uncommitted changes on ${current}; commit or stash them first:\n${dirtyHere}`);
    const sw = deps.git(['switch', branch]);
    if (!sw.ok) throw new KitError(`could not switch to ${branch}: ${sw.err}`);
  }
  const dirty = deps.git(['status', '--porcelain']).out;
  if (dirty) {
    const message = `WIP: handoff from ${previous}`;
    const ok =
      opts.yes ||
      (ctx.io.interactive &&
        (await (ctx.prompts ?? clackPrompts).confirm(
          `${branch} has uncommitted changes from ${previous}:\n${dirty}\nCommit them as "${message}"?`,
          true,
        )));
    if (!ok) {
      throw new KitError(
        `${branch} has uncommitted changes from ${previous}:\n${dirty}\n` +
          `Commit them yourself, or run again with --yes to commit them as "${message}".`,
      );
    }
    const add = deps.git(['add', '-A']);
    const commit = add.ok ? deps.git(['commit', '-m', message]) : add;
    if (!commit.ok) throw new KitError(`could not commit the leftover changes: ${commit.err}`);
    log(`[run] committed leftover changes: "${message}"`);
  }

  // ---------- tell ClickUp and the handoff file ----------
  const last = await deps.lastResult(client!, id);
  const round = Math.max(1, last?.rounds ?? 0);
  await client!.postComment(
    id,
    formatAgentComment({
      agent: 'orchestrator',
      result: 'STARTED',
      round,
      summary:
        `Resumed with ${runner} after ${previous}. Branch ${branch}, continuing round ${round}` +
        `${last ? ` (last: ${last.agent} ${last.result})` : ''}.`,
      next: last?.next ?? 'orchestrator',
    }),
  );
  recordRunStart(ctx, id, runner, previous);
  log(`[run] on branch ${branch}; posted the resume comment`);

  if (!command) {
    log(
      opts.agent === false
        ? `[run] branch ready. Start the agent yourself with this prompt:\n  ${prompt}`
        : `[run] ${runner} has no headless runner. Open this project in Antigravity and type:\n  /start-task ${id}\n  then add: ${prompt}`,
    );
    return;
  }
  if (!(await adapter.isInstalled())) throw new KitError(`${adapter.name} is not available. ${adapter.installHint}`);

  const code = await deps.runAgent(command);
  const result = await deps.lastResult(client!, id);
  const after = await client!.getTask(id, { subtasks: false });
  log('\n[run] summary');
  log(
    `  ${id}: resumed with ${runner}, agent exit ${code ?? 'killed'}, status "${after.status?.status ?? '?'}", ` +
      `${result ? `last result ${result.agent} ${result.result} (round ${result.round ?? '?'})` : 'no agent comment found'}`,
  );
  const leftover = deps.git(['status', '--porcelain', '--untracked-files=no']).out;
  if (leftover) log(`  STOPPED: ${id} left uncommitted changes on ${branch}:\n${leftover}`);
  else deps.git(['switch', config.pipeline.baseBranch]);
  log('  Nothing was pushed. Review the task branch locally.');
}
